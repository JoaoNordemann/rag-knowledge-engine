import chromadb
from chromadb.utils import embedding_functions

# Cria o cliente local do ChromaDB (em memória)
chroma_client = chromadb.Client()

# Baixa um modelo de embedding open-source super rápido e leve
# Esse modelo transforma qualquer texto em um vetor de 384 dimensões
emb_fn = embedding_functions.SentenceTransformerEmbeddingFunction(model_name="all-MiniLM-L6-v2")

# Cria uma "tabela" (collection) no banco para guardar nossos dados
colecao_conhecimento = chroma_client.create_collection(
    name="base_conhecimento",
    embedding_function=emb_fn
)
print("Banco vetorial criado e modelo de embedding carregado!")

# Textos que queremos que o sistema "aprenda"
documentos = [
    "Ataque Corpo a Corpo: Para realizar um ataque com espada ou machado, role 1d20 e some seu bônus de Força e perícia Luta contra a Defesa do alvo.",
    "Mecânica de Sanidade: Ao presenciar uma criatura do Outro Lado, o investigador deve fazer um teste de Vontade. Falhar resulta na perda de pontos de Sanidade baseados na Presença Aterradora do monstro.",
    "Portas Lógicas: A porta AND (E) é um circuito digital que retorna saída verdadeira (1) única e exclusivamente se todas as suas entradas forem verdadeiras (1).",
    "Preparo de Focaccia: A massa de alta hidratação (90%) precisa descansar em dobras a cada 30 minutos nas primeiras duas horas para desenvolver a rede de glúten antes de assar."
]

# IDs únicos para cada documento
ids_documentos = ["doc_rpg_combate", "doc_rpg_terror", "doc_eletronica_and", "doc_culinaria_massa"]

# Salvando no banco: o ChromaDB vai passar os textos no modelo de embedding automaticamente
colecao_conhecimento.add(
    documents=documentos,
    ids=ids_documentos
)
print("Documentos vetorizados e salvos com sucesso!")

# Note que a pergunta não usa as exatas mesmas palavras do texto original
pergunta = "Como faço para não enlouquecer quando vejo um monstro?"

# Busca no banco os 2 documentos matematicamente mais próximos da pergunta
resultados = colecao_conhecimento.query(
    query_texts=[pergunta],
    n_results=2
)

print(f"Pergunta: {pergunta}\n")
print("Documentos Encontrados:")
for i, texto in enumerate(resultados['documents'][0]):
    distancia = resultados['distances'][0][i]
    print(f"{i+1}º Resultado (Distância: {distancia:.4f}): {texto}")